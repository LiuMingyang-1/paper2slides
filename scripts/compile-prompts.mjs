// Compiles prompts/*.md (frontmatter + body) into src/prompts/generated.ts.
// The Anna bundle upload whitelist does not allow .md, so prompts ship as a JS module.
// Source of truth stays in prompts/*.md.
//
// Frontmatter (simple `key: value` lines; arrays as [a, b]):
//   id, version, maxTokens, temperature, schema, includes
// `includes` are paths under prompts/ whose bodies are inlined where the body
// contains `{{> path}}`, or appended at the end if no marker exists.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const promptsDir = join(root, "prompts");
const outFile = join(root, "src", "prompts", "generated.ts");

function parse(file) {
  const raw = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return { meta: {}, body: raw.trim() };
  const meta = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].trim();
    if (v.startsWith("[") && v.endsWith("]")) {
      v = v.slice(1, -1).split(",").map((s) => s.trim()).filter(Boolean);
    } else if (/^-?\d+(\.\d+)?$/.test(v)) {
      v = Number(v);
    }
    meta[kv[1]] = v;
  }
  return { meta, body: m[2].trim() };
}

const prompts = {};
if (existsSync(promptsDir)) {
  for (const f of readdirSync(promptsDir).filter((f) => f.endsWith(".md") && f !== "README.md").sort()) {
    const { meta, body } = parse(join(promptsDir, f));
    if (!meta.id || typeof meta.version !== "number") {
      throw new Error(`${f}: frontmatter needs id and numeric version`);
    }
    let text = body;
    for (const inc of meta.includes ?? []) {
      const incBody = parse(join(promptsDir, inc)).body;
      const marker = `{{> ${inc}}}`;
      text = text.includes(marker) ? text.split(marker).join(incBody) : `${text}\n\n${incBody}`;
    }
    const vars = [...new Set([...text.matchAll(/\{\{(\w+)\}\}/g)].map((x) => x[1]))];
    prompts[meta.id] = {
      id: meta.id,
      version: meta.version,
      maxTokens: meta.maxTokens ?? 4096,
      temperature: meta.temperature ?? 0.2,
      schema: meta.schema ?? null,
      vars,
      template: text,
      source: `prompts/${f}`,
    };
  }
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/compile-prompts.mjs — do not edit. Edit prompts/*.md instead.\n` +
    `import type { PromptDef } from "./types";\n\n` +
    `export const PROMPTS: Record<string, PromptDef> = ${JSON.stringify(prompts, null, 2)};\n`,
);
console.log(`[prompts] compiled ${Object.keys(prompts).length} prompt(s) → src/prompts/generated.ts`);
